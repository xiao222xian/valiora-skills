// Export the chapter timeline (src/timeline.ts) as a lovstudio/media-edit/v1 manifest so
// timeline_check.py and the delivery report read the same structure the film renders from.
import {writeFileSync, mkdirSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {CHAPTERS, TOTAL_FRAMES, FPS, CUES, chapterEnd} from '../src/timeline.ts'; // Node 24 strips the types

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const sec = (f) => Math.round((f / FPS) * 1000) / 1000;
const manifest = {
  schema: 'lovstudio/media-edit/v1',
  iteration: {phase: process.argv[2] || 'draft', state: 'work/iteration-current.json', plan: 'work/iteration-plan.json', timings: 'work/iteration-timings.json'},
  source: {
    video: null,
    note: 'No recorded footage: every frame is generated by the Remotion project. The chapter timeline is laid on the BGM, so source time = film time.',
    audio: ['public/audio/bgm-master.wav'],
    duration_seconds: sec(TOTAL_FRAMES),
  },
  target: {platform: 'cross-platform', aspect_ratio: '16:9', width: 1920, height: 1080, fps: FPS, duration_target_seconds: sec(TOTAL_FRAMES)},
  opening: {strategy: 'auto', resolved_strategy: 'direct', decision_origin: 'automatic', decision_reason: '无口播与高光素材；开场即片名动画，墨滴到标尺的一笔在 10.0 s 配乐重拍处切入第一章', post_problem_title: {enabled: false}},
  segments: CHAPTERS.map((c, i) => ({
    id: c.id,
    source_start: sec(c.start),
    source_end: sec(chapterEnd(i)),
    start_frame: c.start,
    end_frame: chapterEnd(i),
    role: c.no === 0 ? 'title' : c.no === 14 ? 'index-and-credits' : `era-${String(c.no).padStart(2, '0')}`,
    title: c.era,
    years: c.yearsLabel,
    motif: c.motif,
    transition_in: `${c.transition}/${c.transitionFrames}f`,
    speed: 1.0,
    protected_audio: false,
    bgm: 'full',
  })),
  music_cues: Object.fromEntries(Object.entries(CUES).map(([k, f]) => [k, {frame: f, seconds: sec(f)}])),
  audio: {bgm: 'public/audio/bgm-master.wav', source_track: process.env.FILM_BGM_SOURCE || 'set FILM_BGM_SOURCE', mount: 'single continuous bed at composition root', target_lufs_i: -16, true_peak_ceiling_dbfs: -1},
};
mkdirSync(path.join(root, '..', 'manifest'), {recursive: true});
writeFileSync(path.join(root, '..', 'manifest', 'edit-manifest.json'), JSON.stringify(manifest, null, 2));
console.log(`segments ${manifest.segments.length}, total ${manifest.source.duration_seconds}s`);
