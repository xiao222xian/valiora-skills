#!/bin/bash
# Single-chapter previews. Each chapter gets its own generated entry (src/dev/entry-<id>.tsx) that mounts only
# that chapter on the film timeline with subtitles and HUD (src/dev/harness.tsx), so a broken chapter elsewhere
# never blocks this one: parallel builders each preview their own chapter. Frames are LOCAL to the chapter.
#   tools/preview.sh <id> bundle                                  (re)bundle only
#   tools/preview.sh <id> stills <16x9|9x16|both> <local>...       -> <aspect>-f<local>.jpg
#   tools/preview.sh <id> sheet <16x9|9x16> <every> [from to]      -> sheet-<aspect>.jpg (frame numbers burnt in)
#   tools/preview.sh <id> clip <16x9|9x16> <from> <to>             -> clip-<aspect>.mp4 (half size, no sound)
# The chapter's component is read from its `  <id>: <Component>,` line in src/scenes/index.ts and imported from
# ../scenes/<Component> (file name = component name).
# env: PREVIEW_DIR (default ../qc/preview; output goes to <dir>/<id>/), SCALE (stills, default 0.5),
#      REBUNDLE=0 reuses the last bundle, CONC (sheet/clip, default 2), GL (e.g. angle for WebGL scenes),
#      MODULE=../scenes/S07TangB previews another module in this chapter's slot (its export has the file's name)
set -euo pipefail
[ $# -ge 2 ] || { sed -n '2,13p' "$0" >&2; exit 2; }
ID=$1; MODE=$2; shift 2
cd "$(dirname "$0")/.."
NAME=$(sed -n "s/^  $ID: \(S[0-9A-Za-z_]*\),$/\1/p" src/scenes/index.ts)
[ -n "$NAME" ] || { echo "unknown chapter id: $ID (no '  $ID: Sxx...,' line in src/scenes/index.ts)" >&2; exit 1; }
MODULE=${MODULE:-../scenes/$NAME}
EXPORT=$(basename "$MODULE")
tl() { node --disable-warning=MODULE_TYPELESS_PACKAGE_JSON -e "import('./src/timeline.ts').then(m=>{const i=m.CHAPTERS.findIndex(c=>c.id==='$ID');$1})"; }
START=$(tl 'console.log(m.CHAPTERS[i].start)')
OUT=${PREVIEW_DIR:-../qc/preview}/$ID; BUILD=../build/preview-$ID
mkdir -p "$OUT" src/dev
ENTRY=src/dev/entry-$ID.tsx
cat > "$ENTRY" <<TS
// Generated by tools/preview.sh: only the $ID chapter, so other chapters cannot break this bundle.
import {registerRoot} from 'remotion';
import {harnessRoot} from './harness';
import {$EXPORT as Scene} from '$MODULE';
registerRoot(harnessRoot('$ID', Scene));
TS
if [ "${REBUNDLE:-1}" = "1" ] || [ ! -d "$BUILD" ] || [ "$MODE" = "bundle" ]; then
  tools/bundle.sh "$ENTRY" "$BUILD"
fi
[ "$MODE" = "bundle" ] && { echo "bundled $BUILD"; exit 0; }
abs() { echo $(( START + $1 )); }
case "$MODE" in
  stills)
    ASP=$1; shift
    [ "$ASP" = "both" ] && ASPS="16x9 9x16" || ASPS=$ASP
    for a in $ASPS; do
      args=(); for f in "$@"; do args+=("$(abs "$f"):f$f"); done
      node tools/stills.mjs "$BUILD" "H-$a" "$OUT/$a-" "${SCALE:-0.5}" "${args[@]}"
    done ;;
  sheet)
    ASP=$1; EVERY=$2; FROM=${3:-0}; TO=${4:-}
    [ -n "$TO" ] || TO=$(tl 'console.log(m.chapterDur(i)-1)')
    TMP=$(mktemp -d "${TMPDIR:-/tmp}/sheet_XXXXXX")
    npx remotion render "$BUILD" "H-$ASP" "$TMP" --sequence --frames="$(abs "$FROM")-$(abs "$TO")" --every-nth-frame="$EVERY" \
      --image-format=jpeg --jpeg-quality=82 --scale=0.25 --log=error --concurrency="${CONC:-2}" ${GL:+--gl=$GL} >/dev/null
    N=$(ls "$TMP" | wc -l | tr -d ' ')
    [ "$ASP" = "9x16" ] && COLS=6 || COLS=4
    ROWS=$(( (N + COLS - 1) / COLS ))
    ffmpeg -v error -y -pattern_type glob -i "$TMP/*.jpeg" -vf "drawtext=text='%{eif\:n*$EVERY+$FROM\:d}':x=6:y=6:fontsize=14:fontcolor=white:box=1:boxcolor=black@0.6,tile=${COLS}x${ROWS}:padding=4:color=white" -frames:v 1 "$OUT/sheet-$ASP.jpg"
    rm -rf "$TMP"; echo "$OUT/sheet-$ASP.jpg ($N frames, local $FROM-$TO every $EVERY)" ;;
  clip)
    ASP=$1; FROM=$2; TO=$3
    npx remotion render "$BUILD" "H-$ASP" "$OUT/clip-$ASP.mp4" --frames="$(abs "$FROM")-$(abs "$TO")" --scale=0.5 --codec=h264 --crf=24 \
      --muted --log=error --concurrency="${CONC:-2}" ${GL:+--gl=$GL}
    echo "$OUT/clip-$ASP.mp4" ;;
  *) echo "mode: bundle|stills|sheet|clip" >&2; exit 1 ;;
esac
